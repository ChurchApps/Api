// Regenerate src/modules/mcp/lessonsRoutes.ts: the LessonsApi (lessons.church / FreePlay) routes the MCP server exposes.
//
// LessonsApi is a separate service, so its routes can't be read from this process's inversify metadata the way
// RouteInventory reads the Api's own. This script scans a LessonsApi checkout's controllers for @controller/@httpX
// decorators instead.
//
//   yarn mcp:lessons-routes [path to LessonsApi checkout]   (defaults to ../LessonsApi)
import * as fs from "fs";
import * as path from "path";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const lessonsRoot = path.resolve(process.argv[2] || path.join(here, "../../LessonsApi"));
const controllersDir = path.join(lessonsRoot, "src/controllers");
const outFile = path.join(here, "../src/modules/mcp/lessonsRoutes.ts");

if (!fs.existsSync(controllersDir)) {
  console.error(`No controllers folder at ${controllersDir}. Pass the LessonsApi checkout path as the first argument.`);
  process.exit(1);
}

const CONTROLLER_RE = /@controller\(\s*"([^"]*)"/;
const METHOD_RE = /@http(Get|Post|Put|Delete|Patch)\(\s*"([^"]*)"[^)]*\)\s*(?:@[^\n]*\s*)*public\s+async\s+(\w+)/g;

interface Route { method: string; path: string; controllerName: string; methodName: string }
const routes: Route[] = [];

for (const file of fs.readdirSync(controllersDir).sort()) {
  if (!file.endsWith("Controller.ts") || file === "LessonsBaseController.ts") continue;
  const src = fs.readFileSync(path.join(controllersDir, file), "utf8");
  const ctrl = CONTROLLER_RE.exec(src);
  if (!ctrl) continue;
  const controllerName = file.replace(/\.ts$/, "");
  for (const m of src.matchAll(METHOD_RE)) {
    routes.push({ method: m[1].toUpperCase(), path: "/lessons" + joinPath(ctrl[1], m[2]), controllerName, methodName: m[3] });
  }
}

routes.sort((a, b) => (a.path === b.path ? a.method.localeCompare(b.method) : a.path.localeCompare(b.path)));

const body = routes.map((r) => `  { method: "${r.method}", path: "${r.path}", controllerName: "${r.controllerName}", methodName: "${r.methodName}" }`).join(",\n");
fs.writeFileSync(
  outFile,
  `// Generated by tools/generate-lessons-routes.ts from the LessonsApi controllers — do not edit by hand.\n` +
    `// Paths carry a /lessons prefix that the MCP proxy strips before forwarding to Environment.lessonsApi.\n\n` +
    `export interface LessonsRoute {\n  method: string;\n  path: string;\n  controllerName: string;\n  methodName: string;\n}\n\n` +
    `export const LESSONS_ROUTES: LessonsRoute[] = [\n${body}\n];\n`
);
console.log(`Wrote ${routes.length} LessonsApi routes to ${path.relative(process.cwd(), outFile)}`);

function joinPath(prefix: string, suffix: string): string {
  const p = prefix.endsWith("/") ? prefix.slice(0, -1) : prefix;
  if (!suffix || suffix === "/") return p || "/";
  return p + (suffix.startsWith("/") ? suffix : "/" + suffix);
}
